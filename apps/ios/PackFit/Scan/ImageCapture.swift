import CoreImage
import Foundation
import ImageIO
import UniformTypeIdentifiers

enum ImageCapture {
    /// Resize to 1024 px long edge, JPEG quality 0.8, return base64.
    static func jpegBase64(from cgImage: CGImage, maxLongEdge: CGFloat = 1024, quality: CGFloat = 0.8) -> String? {
        let width = CGFloat(cgImage.width)
        let height = CGFloat(cgImage.height)
        let longEdge = max(width, height)
        let scale = longEdge > maxLongEdge ? maxLongEdge / longEdge : 1
        let target = CGSize(width: (width * scale).rounded(), height: (height * scale).rounded())

        let ciImage = CIImage(cgImage: cgImage)
        let context = CIContext(options: [.useSoftwareRenderer: false])
        let scaled = ciImage.transformed(by: CGAffineTransform(scaleX: scale, y: scale))
        guard let out = context.createCGImage(scaled, from: CGRect(origin: .zero, size: target)) else {
            return nil
        }

        let data = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(
            data, UTType.jpeg.identifier as CFString, 1, nil
        ) else { return nil }
        CGImageDestinationAddImage(destination, out, [kCGImageDestinationLossyCompressionQuality: quality] as CFDictionary)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return data.base64EncodedString()
    }

